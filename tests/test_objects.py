def _watch_committed_git(monkeypatch):
    """Refuse an unsafe launch before it could invoke any remote helper."""
    calls = []
    original = subprocess.Popen

    def recording(args, *positional, **kwargs):
        command = tuple(str(arg) for arg in args)
        environment = kwargs.get("env")
        assert environment is not None
        assert environment.get("GIT_NO_REPLACE_OBJECTS") == "1"
        assert environment.get("GIT_NO_LAZY_FETCH") == "1"
        assert any(
            arg == "protocol.allow=never" and position > 0
            and command[position - 1] in ("-c", "--config")
            or arg == "-cprotocol.allow=never"
            for position, arg in enumerate(command)
        ), command
        assert not {"fetch", "fetch-pack", "clone"}.intersection(command)
        process = original(args, *positional, **kwargs)
        calls.append((command, dict(environment), process))
        return process

    monkeypatch.setattr(subprocess, "Popen", recording)
    return calls


