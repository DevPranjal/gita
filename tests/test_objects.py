    @pytest.mark.parametrize("operation", ["read_object", "source"])
    def test_over_limit_object_is_refused_before_any_payload_read(self, committed_objects, committed_api, monkeypatch, operation):
        objects = committed_objects
        limit = 1024 if operation == "source" else 16
        boundary_data = b"b" * limit
        boundary = objects.blob(boundary_data)
        oversized = objects.blob(b"x" * (limit + 1))
        small = objects.blob(b"ok")
        commit = objects.commit(objects.tree(((b"large.py", oversized, "blob", 0o100644),)))
        if operation == "source":
            assert int(objects.git("cat-file", "-s", objects.hex(commit)).stdout) <= limit
        expected_header = f"{objects.hex(oversized)} blob {limit + 1}\n".encode("ascii")
        payload_reads = []

        class GuardedOutput:
            def __init__(self, stream):
                self.stream = stream
                self.over_limit = False

            def readline(self, *args, **kwargs):
                header = self.stream.readline(*args, **kwargs)
                self.over_limit = header == expected_header
                return header

            def read(self, size=-1):
                if self.over_limit:
                    payload_reads.append(size)
                    pytest.fail("over-limit payload was read before resource_limit refusal")
                return self.stream.read(size)

            def __getattr__(self, name):
                return getattr(self.stream, name)

        with committed_api.CommittedRepo(objects.root, max_object_bytes=limit) as repository:
            calls = _watch_committed_git(monkeypatch)
            original = subprocess.Popen

            def guarded_popen(args, *positional, **kwargs):
                process = original(args, *positional, **kwargs)
                if "cat-file" in args and any(arg.split("=", 1)[0] == "--batch" for arg in args):
                    assert process.stdout is not None
                    process.stdout = GuardedOutput(process.stdout)
                return process

            monkeypatch.setattr(subprocess, "Popen", guarded_popen)
            assert repository.read_object(boundary).data == boundary_data
            if operation == "source":
                request = lambda: repository.source(commit, b"large.py", oversized, 0o100644, 0, 1)
            else:
                request = lambda: repository.read_object(oversized)
            _committed_error(committed_api, request, code="resource_limit")
            assert payload_reads == []
            assert repository.read_object(small).data == b"ok"
        assert all(process.returncode is not None for _, _, process in calls)

